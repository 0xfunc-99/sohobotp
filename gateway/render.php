<?php
/**
 * Writes the nginx configuration of the gateway from sites.json, and runtime.json (portal address,
 * API key file, CA) from the environment. Run by entrypoint.sh at every start; refuses a bad
 * sites.json (the container then stops with the reason).
 *
 * sites.json: [{"id": "prometheus", "name": "Prometheus", "listen": 9091,
 *               "upstream": "http://prometheus:9090", "allow": ["alice", "bob"] or ["*"],
 *               "hours": 8, "user_header": "X-WEBAUTH-USER",
 *               "tls_cert": "/certs/x.pem", "tls_key": "/certs/x.key", "upstream_ca": "/certs/ca.pem"}]
 */
declare(strict_types=1);

$dir = '/etc/sohobotp-gateway';
$fail = static function (string $why): never {
    fwrite(STDERR, "sohobotp-gateway: sites.json: $why\n");
    exit(1);
};
$sites = json_decode((string) @file_get_contents("$dir/sites.json"), true);
if (!is_array($sites) || [] === $sites || !array_is_list($sites)) {
    $fail('missing, not valid JSON, or not a list of sites (see README.md)');
}
$ids = $ports = [];
$servers = '';
foreach ($sites as $n => $s) {
    $where = 'site ' . ($n + 1);
    $id = (string) ($s['id'] ?? '');
    if (!preg_match('/^[a-z0-9][a-z0-9-]{0,30}$/', $id) || isset($ids[$id])) {
        $fail("$where: \"id\" must be unique, lower-case letters, digits and dashes");
    }
    $ids[$id] = true;
    $port = $s['listen'] ?? null;
    if (!is_int($port) || $port < 1 || $port > 65535 || isset($ports[$port])) {
        $fail("$where: \"listen\" must be a free port number");
    }
    $ports[$port] = true;
    $up = (string) ($s['upstream'] ?? '');
    if (!preg_match('#^https?://[A-Za-z0-9.\-\[\]:]+(/[A-Za-z0-9._~/-]*)?$#', $up)) {
        $fail("$where: \"upstream\" must be http(s)://host:port of the site");
    }
    if ('' === trim((string) ($s['name'] ?? '')) || [] === (array) ($s['allow'] ?? [])) {
        $fail("$where: \"name\" and \"allow\" (user names, or [\"*\"]) are required");
    }
    $header = (string) ($s['user_header'] ?? '');
    if ('' !== $header && !preg_match('/^[A-Za-z0-9-]{1,64}$/', $header)) {
        $fail("$where: \"user_header\" is not a header name");
    }
    $tls = '' !== (string) ($s['tls_cert'] ?? '');
    $files = array_filter([$s['tls_cert'] ?? '', $s['tls_key'] ?? '', $s['upstream_ca'] ?? ''], 'strlen');
    foreach ($files as $f) {
        if (!preg_match('#^/[A-Za-z0-9._/-]+$#', (string) $f) || !is_readable((string) $f)) {
            $fail("$where: cannot read $f");
        }
    }
    $fcgi = "include fastcgi_params;\n        fastcgi_pass 127.0.0.1:9000;\n        fastcgi_param SCRIPT_FILENAME /app/gateway.php;\n        fastcgi_param SOHOBOTP_SITE $id;";
    $servers .= "server {\n"
        . "    listen $port" . ($tls ? ' ssl' : '') . ";\n"
        . ($tls ? "    ssl_certificate {$s['tls_cert']};\n    ssl_certificate_key {$s['tls_key']};\n    ssl_protocols TLSv1.2 TLSv1.3;\n" : '')
        . "    server_name _;\n    absolute_redirect off;\n    client_max_body_size 200m;\n"
        . "    location = /_sohobotp/check {\n        internal;\n        $fcgi\n        fastcgi_param SOHOBOTP_ACTION check;\n        fastcgi_pass_request_body off;\n        fastcgi_param CONTENT_LENGTH \"\";\n    }\n"
        . "    location /_sohobotp/ {\n        $fcgi\n        fastcgi_param SOHOBOTP_ACTION page;\n    }\n"
        . "    location @sohobotp_login {\n        return 302 /_sohobotp/login?next=\$request_uri;\n    }\n"
        . "    location / {\n"
        . "        auth_request /_sohobotp/check;\n"
        . "        auth_request_set \$sohobotp_user \$upstream_http_x_sohobotp_user;\n"
        . "        error_page 401 = @sohobotp_login;\n"
        . "        proxy_pass $up;\n"
        . "        proxy_http_version 1.1;\n"
        . "        proxy_set_header Upgrade \$http_upgrade;\n"
        . "        proxy_set_header Connection \$connection_upgrade;\n"
        . "        proxy_set_header Cookie \$sohobotp_other_cookies;\n"
        . "        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;\n"
        . "        proxy_set_header X-Forwarded-Proto \$scheme;\n"
        . "        proxy_set_header X-Forwarded-Host \$http_host;\n"
        . "        proxy_set_header X-SohobOTP-User \$sohobotp_user;\n"
        . ('' !== $header ? "        proxy_set_header $header \$sohobotp_user;\n" : '')
        . (str_starts_with($up, 'https://') ? ('' !== (string) ($s['upstream_ca'] ?? '') ? "        proxy_ssl_verify on;\n        proxy_ssl_trusted_certificate {$s['upstream_ca']};\n        proxy_ssl_server_name on;\n" : "        proxy_ssl_server_name on;\n") : '')
        . "        proxy_read_timeout 3600s;\n        proxy_buffering off;\n"
        . "    }\n}\n";
}
$conf = "# generated by render.php from sites.json: do not edit\n"
    . "map \$http_upgrade \$connection_upgrade { default upgrade; '' close; }\n"
    // the gateway's session cookie is not passed to the site behind it
    . "map \$http_cookie \$sohobotp_cookies_1 {\n    default \$http_cookie;\n    \"~^(?<before>.*?)(?:^|;\\s*)sohobotp_[a-z0-9-]+=[^;]*(?<after>.*)\$\" \"\$before\$after\";\n}\n"
    // twice: sites on the same host name (other ports) share cookies
    . "map \$sohobotp_cookies_1 \$sohobotp_other_cookies {\n    default \$sohobotp_cookies_1;\n    \"~^(?<before>.*?)(?:^|;\\s*)sohobotp_[a-z0-9-]+=[^;]*(?<after>.*)\$\" \"\$before\$after\";\n}\n"
    . $servers;
file_put_contents('/etc/nginx/conf.d/sohobotp-gateway.conf', $conf);

$runtime = [
    'portal' => (string) getenv('SOHOBOTP_PORTAL'),
    'api_key' => (string) getenv('SOHOBOTP_API_KEY'),
    'api_key_file' => (string) getenv('SOHOBOTP_API_KEY_FILE'),
    'ca' => (string) getenv('SOHOBOTP_CA'),
    'insecure' => '1' === getenv('SOHOBOTP_INSECURE'),
];
if ('' === $runtime['portal'] || ('' === $runtime['api_key'] && '' === $runtime['api_key_file'])) {
    fwrite(STDERR, "sohobotp-gateway: set SOHOBOTP_PORTAL and SOHOBOTP_API_KEY (or SOHOBOTP_API_KEY_FILE)\n");
    exit(1);
}
file_put_contents("$dir/runtime.json", json_encode($runtime, JSON_UNESCAPED_SLASHES));
chmod("$dir/runtime.json", 0640);
chgrp("$dir/runtime.json", 'www-data');
echo 'sohobotp-gateway: ' . count($sites) . ' site(s): ' . implode(', ', array_map(static fn (array $s): string => $s['id'] . ' on port ' . $s['listen'] . ' -> ' . $s['upstream'], $sites)) . "\n";
